// Finds Spider deals that can be won, and writes their seeds to src/model/spider-deals.ts.
//   node scripts/find-solvable-spider-deals.ts <card count> <suit count> <deal count>
// Replaces the list of seeds of that number of cards and suits, and keeps the other lists.
// Each seed is shuffled, the solver plays the deal, and the solution is replayed with the rules of the game.
// Runs one worker per processor; 104 cards with four suits take about 12 seconds per deal found and per processor.
import {availableParallelism} from "node:os";
import {writeFileSync} from "node:fs";
import {isMainThread, parentPort, Worker, workerData} from "node:worker_threads";

import {seededRandom} from "../src/model/deck.model.ts";
import {CARD_COUNT_OPTIONS, dealSeededTable, SUIT_COUNT_OPTIONS, type SpiderVariant} from "../src/model/spider.model.ts";
import {findSolution} from "../src/model/spider-solver.ts";
import {SOLVABLE_DEAL_SEEDS} from "../src/model/spider-deals.ts";

const OUTPUT = new URL("../src/model/spider-deals.ts", import.meta.url);

const isSolvable = (variant: SpiderVariant, seed: number): boolean =>
    findSolution(dealSeededTable(variant, seed)) !== null;

type Result = { seed: number, solvable: boolean };

if (!isMainThread) {
    const variant = workerData as SpiderVariant;
    parentPort?.on("message", (seed: number) => {
        parentPort?.postMessage({seed, solvable: isSolvable(variant, seed)} satisfies Result);
    });
} else {
    const cardCount = Number(process.argv[2]);
    const suitCount = Number(process.argv[3]);
    const wanted = Number(process.argv[4]);
    if (!CARD_COUNT_OPTIONS.includes(cardCount) || !SUIT_COUNT_OPTIONS.includes(suitCount) || !(wanted > 0)) {
        console.error(`usage: node scripts/find-solvable-spider-deals.ts <${CARD_COUNT_OPTIONS.join("|")}> <${SUIT_COUNT_OPTIONS.join("|")}> <deal count>`);
        process.exit(1);
    }
    // the candidate seeds come from a fixed sequence, so that a run can be repeated
    const nextCandidate = (() => {
        const random = seededRandom(cardCount * 10 + suitCount);
        return () => Math.floor(random() * 2 ** 32);
    })();
    const found: number[] = [];
    let tried = 0;
    const started = Date.now();
    const write = () => {
        const lists = {...SOLVABLE_DEAL_SEEDS, [cardCount]: {...SOLVABLE_DEAL_SEEDS[cardCount], [suitCount]: [...found].sort((x, y) => x - y)}};
        const seedLines = (seeds: readonly number[]) => Array.from({length: Math.ceil(seeds.length / 8)}, (_, i) =>
            `            ${seeds.slice(i * 8, i * 8 + 8).join(", ")},`);
        const lines = CARD_COUNT_OPTIONS.flatMap(cards => [
            `    ${cards}: {`,
            ...SUIT_COUNT_OPTIONS.flatMap(suits => {
                const seeds = lists[cards]?.[suits] ?? [];
                return seeds.length === 0 ? [`        ${suits}: [],`] : [`        ${suits}: [`, ...seedLines(seeds), "        ],"];
            }),
            "    },",
        ]);
        writeFileSync(OUTPUT, [
            "// Generated by scripts/find-solvable-spider-deals.ts, do not edit by hand.",
            "// For each number of cards and of suits, the seeds of shuffles (dealSeededTable) whose deal the solver won.",
            "export const SOLVABLE_DEAL_SEEDS: Partial<Record<number, Partial<Record<number, readonly number[]>>>> = {",
            ...lines,
            "};",
            "",
        ].join("\n"));
    };
    const workers = Array.from({length: availableParallelism()}, () =>
        new Worker(new URL(import.meta.url), {workerData: {suitCount, cardCount} satisfies SpiderVariant}));
    workers.forEach(worker => {
        worker.on("message", ({seed, solvable}: Result) => {
            tried++;
            if (solvable && found.length < wanted) {
                found.push(seed);
                const seconds = Math.round((Date.now() - started) / 1000);
                console.log(`${found.length}/${wanted} found, ${tried} tried, ${seconds} s`);
                if (found.length % 20 === 0 || found.length === wanted) write();
            }
            if (found.length >= wanted) void Promise.all(workers.map(w => w.terminate()));
            else worker.postMessage(nextCandidate());
        });
        worker.postMessage(nextCandidate());
    });
}
